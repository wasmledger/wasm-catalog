// pnpm demo:data — export a built catalog for the web browser (WCT-024) and write the
// near-duplicate report (WCT-018). Offline: reads the recorded harvest and build only.
//
//   node scripts/web-data.ts [--index out/full/index.json] [--catalog out/full/catalog]
//     [--harvest out/harvest-full/harvest.json] [--coverage census/full-walk-2026-11-04/coverage.json]
//     [--out web/public/data] [--report census/full-walk-2026-11-04/SIMILARITY.md]
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { gzipSync } from "node:zlib";
import type { Harvest } from "../src/harvest.ts";
import { buildWebData, WEB_SHARD_FORMAT, type CatalogIndex, type Group, type SpecJson } from "../src/webdata.ts";

const root = join(import.meta.dirname, "..");
const { values: v } = parseArgs({
  options: {
    index: { type: "string", default: "out/full/index.json" },
    catalog: { type: "string", default: "out/full/catalog" },
    harvest: { type: "string", default: "out/harvest-full/harvest.json" },
    coverage: { type: "string", default: "census/full-walk-2026-11-04/coverage.json" },
    out: { type: "string", default: "web/public/data" },
    report: { type: "string", default: "census/full-walk-2026-11-04/SIMILARITY.md" },
  },
});
const p = (x: string) => join(root, x);
for (const k of ["index", "catalog", "harvest", "coverage"] as const) {
  if (!existsSync(p(v[k]))) {
    console.error(`missing ${k}: ${v[k]}. The web data is committed under web/public/data; regenerating it needs the recorded full harvest and build in out/ (see DEMO.md).`);
    process.exit(2);
  }
}

const readJson = <T>(f: string): T => JSON.parse(readFileSync(f, "utf8")) as T;
const t0 = Date.now();
const data = buildWebData({
  index: readJson<CatalogIndex>(p(v.index)),
  harvest: readJson<Harvest>(p(v.harvest)),
  coverage: readJson<Record<string, unknown>>(p(v.coverage)),
  readSpec: (h) => {
    const f = join(p(v.catalog), h, "spec.json");
    return existsSync(f) ? readJson<SpecJson>(f) : null;
  },
  readBindings: (h) => {
    const f = join(p(v.catalog), h, "bindings.ts");
    return existsSync(f) ? readFileSync(f, "utf8") : null;
  },
  exportedAt: new Date().toISOString(),
});

// Write to a temp dir, then swap, so an interrupted run never leaves a half tree.
const out = p(v.out);
const tmp = `${out}.tmp-${process.pid}`;
rmSync(tmp, { recursive: true, force: true });
mkdirSync(join(tmp, "h"), { recursive: true });
mkdirSync(join(tmp, "c"), { recursive: true });
let bytes = 0;
const put = (rel: string, body: string | Uint8Array) => {
  writeFileSync(join(tmp, rel), body);
  bytes += body.length;
};
put("summary.json", `${JSON.stringify(data.summary, null, 1)}\n`);
put("index.json", JSON.stringify(data.index));
for (const [k, s] of [...data.shards].sort()) put(`h/${k}.json.gz`, gzipSync(JSON.stringify({ format: WEB_SHARD_FORMAT, hashes: s }), { level: 9 }));
for (const [k, s] of [...data.contractShards].sort()) put(`c/${k}.json.gz`, gzipSync(JSON.stringify(s), { level: 9 }));
rmSync(out, { recursive: true, force: true });
renameSync(tmp, out);

// Near-duplicate report.
const s = data.summary as { provenance: { latestLedger: number; harvestedAt: string }; groups: Record<string, { groups?: number; clusters?: number; hashes: number; top: Group[] }> & { near: { options: Record<string, number>; considered: number; distinctSets: number; edges: number; clusters: number; hashes: number; top: Group[]; method: string } }; seps: Record<string, { hashes: number; contracts: number; method?: string }> };
const near = s.groups.near;
const short = (h: string) => `\`${h.slice(0, 8)}…${h.slice(-6)}\``;
const lines = [
  "# Near-duplicate depth (WCT-018)",
  "",
  "<!-- SPDX-License-Identifier: Apache-2.0 -->",
  "",
  `Generated by \`node scripts/web-data.ts\` from the recorded full walk (harvest ${s.provenance.harvestedAt}, latest ledger ${s.provenance.latestLedger}). Measured [P]; method below.`,
  "",
  "## Method",
  "",
  `- ${near.method}.`,
  `- Threshold ${near.options["threshold"]} (Jaccard), minimum ${near.options["minFunctions"]} functions, neighbours kept per hash: ${near.options["neighbours"]} at Jaccard >= ${near.options["neighbourFloor"]}.`,
  "- Single linkage can chain: a cluster's minimum edge score is reported per cluster; two members of one cluster may be less similar than the threshold.",
  "- Template labels are checked from the spec alone: SEP-41 means the ten SEP-41 functions are present with the SEP's input counts. Types are not compared, so a label says the interface has that shape, not that the code behaves as SEP-41 requires.",
  "",
  "## Results",
  "",
  "| Measure | Value |",
  "|---|---|",
  `| Hashes considered (>= ${near.options["minFunctions"]} functions) | ${near.considered} |`,
  `| Distinct function-name sets | ${near.distinctSets} |`,
  `| Pairs of distinct sets at Jaccard >= ${near.options["threshold"]} | ${near.edges} |`,
  `| Near-duplicate clusters (2+ hashes) | ${near.clusters}, covering ${near.hashes} hashes |`,
  `| Exact groups: same interface / same spec bytes / same code | ${s.groups["sameInterface"]!.groups} / ${s.groups["sameSpec"]!.groups} / ${s.groups["sameCode"]!.groups} |`,
  `| SEP-41 function set | ${s.seps["sep41"]!.hashes} hashes, ${s.seps["sep41"]!.contracts} contracts |`,
  `| SEP-41 plus SAC admin functions | ${s.seps["sep41SacAdmin"]!.hashes} hashes, ${s.seps["sep41SacAdmin"]!.contracts} contracts |`,
  `| SEP-41 partial (7-9 names, or arity differs) | ${s.seps["sep41Partial"]!.hashes} hashes, ${s.seps["sep41Partial"]!.contracts} contracts |`,
  "",
  "## Largest near-duplicate clusters",
  "",
  "| Hashes | Distinct sets | Min edge | Contracts | Shared functions | soroban-sdk | Largest members |",
  "|--:|--:|--:|--:|---|---|---|",
  ...near.top.slice(0, 15).map((g) => `| ${g.size} | ${g.distinctSets} | ${g.minJ?.toFixed(3)} | ${g.contracts} | ${g.shared?.length ?? 0} of ${g.unionSize} | ${g.sdkVersions.slice(0, 4).join(", ")}${g.sdkVersions.length > 4 ? ", …" : ""} | ${g.members.slice(0, 3).map(short).join(" ")} |`),
  "",
  "Function names are untrusted on-chain strings and are not printed here; see the web catalog for each cluster.",
  "",
];
writeFileSync(p(v.report), lines.join("\n"));
console.log(`web data: ${data.index.count} hashes, ${data.shards.size} hash shards, ${data.contractShards.size} contract shards, ${(bytes / 1e6).toFixed(1)} MB in ${v.out} (${((Date.now() - t0) / 1000).toFixed(1)} s); report ${v.report}`);
